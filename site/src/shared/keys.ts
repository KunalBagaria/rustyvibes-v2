/** The app's spatial-stereo pan for a key centre: ±PAN_WIDTH across the main block. */
export function panForX(x: number): number {
  return Math.min(1, Math.max(-1, (x - 7.25) / 7.75)) * PAN_WIDTH;
}

export function panForKeycode(kvk: number): number {
  const x = KVK_X[kvk];
  return x === undefined ? 0 : panForX(x);
}
